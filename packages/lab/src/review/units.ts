import { FIRST, type AttentionKind, type Category, type Excerpt, type Guide } from "./data";

export type Cut = "stops" | "groups" | "sections" | "order";

export interface UnitFile {
  readonly path: string;
  readonly note: string | null;
}

export interface Unit {
  readonly id: string;
  readonly mark: string | null;
  readonly title: string;
  readonly why: string | null;
  readonly attention: { readonly kind: AttentionKind; readonly note: string } | null;
  readonly excerpts: readonly Excerpt[];
  readonly diffs: boolean;
  readonly files: readonly UnitFile[];
  readonly questions: readonly string[];
  readonly folded: boolean;
}

const GROUPS: readonly {
  readonly category: Category;
  readonly title: string;
  readonly why: string;
}[] = [
  {
    category: "core",
    title: "Empty reasons",
    why: "The summary says why the list is empty.",
  },
  {
    category: "ui",
    title: "Empty state",
    why: "The component and where the panel shows it.",
  },
  { category: "config", title: "Spacing token", why: "A new space step for the padding." },
  { category: "tests", title: "Tests", why: "One row per reason, and the filtered count." },
  { category: "docs", title: "Docs", why: "What a full filter shows." },
  { category: "generated", title: "Generated", why: "Regenerated by lock:tokens." },
];

const SORTED: readonly { readonly title: string; readonly categories: readonly Category[] }[] = [
  { title: "Implementation", categories: ["core", "ui", "config"] },
  { title: "Tests", categories: ["tests"] },
  { title: "Docs", categories: ["docs"] },
  { title: "Generated", categories: ["generated"] },
];

export function units(cut: Cut, guide: Guide): readonly Unit[] {
  if (cut === "groups") return groups(guide);

  if (cut === "sections") return sections(guide);

  if (cut === "order") return order(guide);

  return guide.stops.map((stop, index) => ({
    id: stop.id,
    mark: String(index + 1),
    title: stop.title,
    why: stop.why,
    attention: stop.attention,
    excerpts: stop.excerpts,
    diffs: false,
    files: stop.files,
    questions: stop.questions,
    folded: false,
  }));
}

export function sorted(): readonly Unit[] {
  return SORTED.map((group) => ({
    id: group.title,
    mark: null,
    title: group.title,
    why: null,
    attention: null,
    excerpts: [],
    diffs: false,
    files: FIRST.files
      .filter((file) => group.categories.includes(file.category))
      .map((file) => ({ path: file.path, note: null })),
    questions: [],
    folded: false,
  }));
}

function noteFor(guide: Guide, path: string): string | null {
  return guide.stops.flatMap((stop) => stop.files).find((file) => file.path === path)?.note ?? null;
}

function groups(guide: Guide): readonly Unit[] {
  return GROUPS.map((group) => {
    const files = FIRST.files.filter((file) => file.category === group.category);

    const flagged = guide.stops.find(
      (stop) =>
        stop.attention !== null &&
        stop.files.some((entry) => files.some((file) => file.path === entry.path)),
    );

    return {
      id: group.category,
      mark: group.category,
      title: group.title,
      why: group.why,
      attention: flagged?.attention ?? null,
      excerpts: [],
      diffs: group.category === "core" || group.category === "ui",
      files: files.map((file) => ({ path: file.path, note: noteFor(guide, file.path) })),
      questions: [],
      folded: false,
    };
  });
}

function sections(guide: Guide): readonly Unit[] {
  const core = guide.stops.slice(0, 3);
  const rest = guide.stops.slice(3);

  return [
    ...core.map((stop) => ({
      id: stop.id,
      mark: null,
      title: stop.title,
      why: stop.why,
      attention: null,
      excerpts: stop.excerpts,
      diffs: false,
      files: stop.files,
      questions: [],
      folded: false,
    })),
    {
      id: "supporting",
      mark: null,
      title: "Supporting changes",
      why: "Tests, docs and generated files.",
      attention: null,
      excerpts: [],
      diffs: false,
      files: rest.flatMap((stop) => stop.files),
      questions: [],
      folded: true,
    },
  ];
}

function order(guide: Guide): readonly Unit[] {
  return guide.stops
    .flatMap((stop) => stop.files)
    .map((file) => ({
      id: file.path,
      mark: null,
      title: file.path.split("/").at(-1) ?? file.path,
      why: file.note,
      attention: null,
      excerpts: [],
      diffs: true,
      files: [{ path: file.path, note: null }],
      questions: [],
      folded: false,
    }));
}

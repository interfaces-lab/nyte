#!/usr/bin/env python3
"""Generates the file-type icon table from @pierre/trees (Apache-2.0).

Usage: generate-file-icons.py <path to pierre/packages/trees/src> > Sources/NyteUI/FileIconData.generated.swift
"""
import re
import sys

source = sys.argv[1]
icons = open(f"{source}/builtInIcons.ts").read()
style = open(f"{source}/style.css").read()

symbols = {
    name: " ".join(body.split())
    for name, body in re.findall(r'<symbol id="([^"]+)" viewBox="0 0 16 16">(.*?)</symbol>', icons, re.S)
}
palette = {
    name: (light, dark)
    for name, light, dark in re.findall(r"--trees-icon-([a-z]+): light-dark\((#[0-9a-f]{6}), (#[0-9a-f]{6})\)", style)
}
hue = dict(
    re.findall(r"--trees-file-icon-color-([a-z]+): var\(\s*--trees-file-icon-color,\s*var\(--trees-icon-([a-z]+)\)", style)
)

def table(name):
    start = icons.index(name)
    body = icons[icons.index("{", icons.index("=", start)) : icons.index("};", start)]
    return re.findall(r"""['"]?([^\s'":,{]+)['"]?:\s*'([a-z]+)'""", body)

tokens = sorted(name[len("file-tree-builtin-"):] for name in symbols if name.startswith("file-tree-builtin-"))
tokens.remove("default")
tokens.insert(0, "default")
index = {token: position for position, token in enumerate(tokens)}
extensions = dict(table("BUILT_IN_FILE_EXTENSION_TOKENS"))
extensions.update(table("COMPLETE_EXTENSION_OVERRIDES"))

def swift(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

def colour(token, mode):
    light, dark = palette[hue.get(token, "gray")]
    return "0x" + (light if mode == "light" else dark)[1:].upper()

print("// Generated by the file-icon generator script from @pierre/trees (Apache-2.0). Do not edit.")
print("// swiftformat:disable all")
print()
print("enum FileIconData {")
print("    static let names: [String] = [" + ", ".join(swift(token) for token in tokens) + "]")
print()
print("    static let light: [UInt32] = [" + ", ".join(colour(token, "light") for token in tokens) + "]")
print()
print("    static let dark: [UInt32] = [" + ", ".join(colour(token, "dark") for token in tokens) + "]")
print()
print("    static let markup: [String] = [")
for token in tokens:
    print("        " + swift(symbols["file-tree-builtin-" + token]) + ",")
print("    ]")
print()
print("    static let chevron = " + swift(symbols["file-tree-icon-chevron"]))
print()
print("    static let byFileName: [String: UInt8] = [")
for key, token in sorted(table("BUILT_IN_FILE_NAME_TOKENS")):
    print(f"        {swift(key.lower())}: {index[token]},")
print("    ]")
print()
print("    static let byExtension: [String: UInt8] = [")
for key, token in sorted((key.lower(), token) for key, token in extensions.items()):
    print(f"        {swift(key)}: {index[token]},")
print("    ]")
print("}")

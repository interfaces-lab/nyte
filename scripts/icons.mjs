#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * @type {readonly {
 *   name: string,
 *   package: string,
 *   central: readonly string[],
 *   selected: string,
 *   sets: Readonly<Record<"central" | "lucide", string>>,
 * }[]}
 */
export const ICON_CONSUMERS = [
  {
    name: "ui",
    package: "packages/ui",
    central: ["central-icons", "central-icons-filled"],
    selected: "src/glyphs/selected.generated.ts",
    sets: { central: "./central.tsx", lucide: "./lucide.ts" },
  },
  {
    name: "docs",
    package: "packages/docs",
    central: ["central-icons"],
    selected: "src/lib/icon-set/selected.generated.ts",
    sets: { central: "./central.ts", lucide: "./lucide.ts" },
  },
  {
    name: "mobile",
    package: "packages/mobile",
    central: ["central-icons"],
    selected: "scripts/icon-set/selected.generated.mjs",
    sets: { central: "./central.mjs", lucide: "./lucide.mjs" },
  },
];

function centralInstalled(consumer) {
  return consumer.central.every((alias) =>
    existsSync(join(root, consumer.package, "node_modules", alias, "package.json")),
  );
}

/**
 * The set a package builds with. Throws when NYTE_ICONS asks for Central and
 * it isn't installed, since a silent fallback would hide the mismatch.
 *
 * @returns {"central" | "lucide"}
 */
export function iconSet(name, env = process.env) {
  const consumer = ICON_CONSUMERS.find((entry) => entry.name === name);

  if (consumer === undefined) throw new Error(`No icon consumer named ${name}.`);
  const requested = env["NYTE_ICONS"];

  if (requested === "lucide") return "lucide";

  if (requested === "central") {
    if (centralInstalled(consumer)) return "central";
    throw new Error(
      `NYTE_ICONS=central, but Central Icons aren't installed in ${consumer.package}. ` +
        "Set CENTRAL_LICENSE_KEY and run pnpm install, or unset NYTE_ICONS.",
    );
  }

  if (requested !== undefined && requested !== "") {
    throw new Error(`NYTE_ICONS must be central or lucide, not ${JSON.stringify(requested)}.`);
  }

  return centralInstalled(consumer) ? "central" : "lucide";
}

function selectedSource(consumer, set) {
  const reason =
    set === "central" ? "Central Icons are installed" : "Central Icons aren't installed";

  return [
    `// Generated by scripts/icons.mjs (${reason}). Do not edit; NYTE_ICONS=central|lucide overrides.`,
    `export * from "${consumer.sets[set]}";`,
    "",
  ].join("\n");
}

export function selectIcons(env = process.env) {
  return ICON_CONSUMERS.map((consumer) => {
    const set = iconSet(consumer.name, env);
    const path = join(root, consumer.package, consumer.selected);
    const source = selectedSource(consumer, set);
    const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
    const changed = current !== source;

    if (changed) writeFileSync(path, source);

    return { name: consumer.name, set, path: relative(root, path), changed };
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const results = selectIcons();
    const sets = new Set(results.map((result) => result.set));

    const summary =
      sets.size === 1
        ? `icons: ${[...sets][0]}`
        : `icons: ${results.map((result) => `${result.name} ${result.set}`).join(", ")}`;

    process.stderr.write(`${summary}\n`);
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
